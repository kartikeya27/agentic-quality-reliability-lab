"""Real HTTP proof that container app, Prometheus scraping and Grafana dashboard work.

Requires `docker compose up -d` first; this script cannot produce a passing report
without the actual services responding. Uses only localhost-bound ports.
"""
import argparse
import json
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx


def _await_http(url: str, timeout: int = 90):
    end = time.monotonic() + timeout
    last = None
    while time.monotonic() < end:
        try:
            resp = httpx.get(url, timeout=4)
            if resp.status_code == 200:
                return resp
            last = f"HTTP {resp.status_code}"
        except httpx.HTTPError as exc:
            last = type(exc).__name__
        time.sleep(2)
    raise RuntimeError(f"{url} failed to become healthy: {last}")


def check_stack() -> dict:
    api = 'http://127.0.0.1:8000'
    prometheus = 'http://127.0.0.1:9090'
    grafana = 'http://127.0.0.1:3000'
    result = {"generated_at": datetime.now(timezone.utc).isoformat(), "checks": {}, "verified": False}
    health = _await_http(api + '/api/health').json()
    result['checks']['api_health'] = health.get('status') == 'ok'
    payload = {"incident_id": "DOCKER-SMOKE", "message": "Database query failed"}
    resp = httpx.post(api + '/api/triage', json=payload, timeout=15)
    resp.raise_for_status()
    result['checks']['api_triage'] = resp.json()['runbook_id'] == 'RB-DATABASE-02'
    metrics = _await_http(api + '/metrics').text
    result['checks']['prometheus_exposition'] = 'aq_triage_requests_total' in metrics and 'aq_qa_pass_ratio' in metrics
    _await_http(prometheus + '/-/ready')
    # Prometheus executes a query against real scraped metrics. Retry for scrape delay.
    query_ok = False
    for _ in range(15):
        response = httpx.get(prometheus + '/api/v1/query', params={'query': 'up{job="agent-quality-lab"}'}, timeout=6)
        response.raise_for_status()
        series = response.json().get('data', {}).get('result', [])
        if any(float(s['value'][1]) == 1.0 for s in series):
            query_ok = True
            break
        time.sleep(2)
    result['checks']['prometheus_scraping_up'] = query_ok
    # Confirm that a triage counter generated by this test reached Prometheus.
    triage_metric_seen = False
    for _ in range(15):
        response = httpx.get(prometheus + '/api/v1/query',
                             params={'query': 'sum(aq_triage_requests_total{mode="deterministic"})'}, timeout=6)
        response.raise_for_status()
        series = response.json().get('data', {}).get('result', [])
        if any(float(s['value'][1]) >= 1.0 for s in series):
            triage_metric_seen = True
            break
        time.sleep(2)
    result['checks']['prometheus_scraped_real_triage_counter'] = triage_metric_seen
    _await_http(grafana + '/api/health')
    dashboards = httpx.get(grafana + '/api/search', params={'query': 'Agent Quality'}, timeout=10)
    dashboards.raise_for_status()
    result['checks']['grafana_dashboard_provisioned'] = any(x.get('uid') == 'agent-quality-lab' for x in dashboards.json())
    dash = httpx.get(grafana + '/api/dashboards/uid/agent-quality-lab', timeout=10)
    dash.raise_for_status()
    panel_data = dash.json().get('dashboard', {})
    result['checks']['grafana_dashboard_has_panels'] = (
        panel_data.get('uid') == 'agent-quality-lab' and len(panel_data.get('panels', [])) >= 5
    )
    datasources = httpx.get(grafana + '/api/datasources', timeout=10)
    datasources.raise_for_status()
    result['checks']['grafana_prometheus_datasource'] = any(x.get('type') == 'prometheus' for x in datasources.json())
    result['verified'] = all(result['checks'].values())
    return result


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--out', default='artifacts/docker-stack-report.json')
    args = p.parse_args()
    try:
        report = check_stack()
    except (httpx.HTTPError, KeyError, ValueError, RuntimeError) as exc:
        report = {'verified': False, 'error': f'{type(exc).__name__}: {exc}'}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    if not report['verified']:
        raise SystemExit('Docker stack NOT verified; inspect service logs with docker compose logs')


if __name__ == '__main__':
    main()
